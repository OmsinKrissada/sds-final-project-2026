#!/usr/bin/env bash
# Writes deploy/generated/ (gitignored) from .env:
#   deploy/generated/kustomization.yaml          -> apply with `kubectl apply -k deploy/generated`
#   deploy/generated/prepull/                     -> apply with `kubectl apply -k deploy/generated/prepull`
# Usage: scripts/render.sh [base|ha]     (default: base; or HA=1 in env)
set -euo pipefail
. "$(dirname "$0")/lib.sh"
load_env
need REGISTRY DB_HOST
TAG="${TAG:-latest}"
REGISTRY="${REGISTRY%/}"
MODE="${1:-}"
[ -n "$MODE" ] || { [ "${HA:-0}" = 1 ] && MODE=ha || MODE=base; }
case "$MODE" in
  base) RES="../base" ;;
  ha)   RES="../overlays/ha" ;;
  *) echo "usage: $0 [base|ha]" >&2; exit 2 ;;
esac
SVCS="gateway frontend account quiz game"

OUT="$ROOT/deploy/generated"
mkdir -p "$OUT/prepull"

# $1 = prefix of the image name to match. deploy/base already renames
# quizbox-<svc> to ghcr.io/OWNER/quizbox-<svc>:latest, and kustomize applies the
# outer images: entry to that result, so the generated file must match the
# placeholder name. prepull.yaml has no base and uses the bare names.
images() {
  echo "images:"
  for s in $SVCS; do
    printf '  - name: %squizbox-%s\n    newName: %s/quizbox-%s\n    newTag: "%s"\n' "$1" "$s" "$REGISTRY" "$s" "$TAG"
  done
}

{
  echo "# GENERATED by scripts/render.sh ($MODE) - do not edit, do not commit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  echo "  - $RES"
  images "ghcr.io/OWNER/"
  cat <<YAML
patches:
  - target:
      group: discovery.k8s.io
      version: v1
      kind: EndpointSlice
      name: postgres
    patch: |-
      - op: replace
        path: /endpoints/0/addresses/0
        value: "$DB_HOST"
YAML
} > "$OUT/kustomization.yaml"

# Pre-pull DaemonSet: kustomize may not load files outside its root, so copy it in.
cp "$ROOT/deploy/prepull.yaml" "$OUT/prepull/prepull.yaml"
{
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "namespace: quizbox"
  echo "resources:"
  echo "  - prepull.yaml"
  images ""
} > "$OUT/prepull/kustomization.yaml"

echo "rendered $OUT ($MODE): registry=$REGISTRY tag=$TAG postgres=$DB_HOST" >&2
